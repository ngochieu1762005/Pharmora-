#!/usr/bin/env python3
"""Build the single offline-safe PharmaVision stylesheet.

Edit the source CSS files, then run:
    python tools/build_assets.py
    python tools/build_assets.py --check
No Node.js or package installation is required.
"""
from __future__ import annotations
import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
CSS = ROOT / "static"
SOURCES = ("styles.css", "mobile.css", "design.css", "typography.css", "polish.css")
OUTPUT = CSS / "app.css"
HEADER = "/* PharmaVision UI bundle. Generated by tools/build_assets.py. Do not edit this file directly. */\n"


def build_css() -> str:
    chunks = []
    for filename in SOURCES:
        path = CSS / filename
        chunks.append("\n/* ---- static/" + filename + " ---- */\n" + path.read_text(encoding="utf-8").rstrip() + "\n")
    return HEADER + "".join(chunks)


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--check", action="store_true", help="Fail when the checked-in CSS bundle is outdated")
    args = p.parse_args()
    generated = build_css()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != generated:
            print("ERROR: static/app.css is outdated. Run: python tools/build_assets.py", file=sys.stderr)
            return 1
        print("OK: static/app.css is up to date")
        return 0
    OUTPUT.write_text(generated, encoding="utf-8", newline="\n")
    print(f"Built {OUTPUT} from {len(SOURCES)} CSS source files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
